#!/usr/bin/env node
/**
 * Setup for dendrite-admin-mcp.
 *
 * Writes a .env from your answers (or flags), installs dependencies, builds,
 * runs the test suite, and prints the exact MCP registration snippet for your
 * agent (Claude Code, Codex, OpenCode, GitHub Copilot, Pi, ...).
 *
 * Usage:
 *   npm run setup                                  # interactive prompts
 *   npm run setup -- --base-url https://matrix.example.com \
 *     --admin-token <token> [--shared-secret <secret>] \
 *     [--transport stdio|http] [--mcp-token <token>] \
 *     [--skip-install] [--skip-build] [--skip-test]
 *
 * Value resolution order: CLI flag > shell env var > existing .env > prompt.
 * Prompts are skipped when stdin is not a TTY (e.g. when an agent runs this).
 */
import { createInterface } from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const ENV_FILE = path.join(ROOT, ".env");
const DIST_INDEX = path.join(ROOT, "dist", "index.js");

const REQUIRED_VARS = [
  {
    key: "DENDRITE_BASE_URL",
    flag: "base-url",
    prompt: "Dendrite homeserver base URL (client-facing port, no trailing slash)",
    example: "https://matrix.example.com",
  },
  {
    key: "DENDRITE_ADMIN_TOKEN",
    flag: "admin-token",
    prompt: "Dendrite admin user access token (Bearer token for /_dendrite/admin)",
    example: "syt_... (from your admin user's account)",
  },
];

const OPTIONAL_VARS = [
  {
    key: "DENDRITE_REGISTRATION_SHARED_SECRET",
    flag: "shared-secret",
    prompt: "registration_shared_secret from dendrite.yaml (only needed for register_user)",
    example: "leave blank to skip",
  },
];

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith("--")) continue;
    const eq = a.indexOf("=");
    if (eq !== -1) {
      args[a.slice(2, eq)] = a.slice(eq + 1);
      continue;
    }
    const key = a.slice(2);
    const next = argv[i + 1];
    if (next !== undefined && !next.startsWith("--")) {
      args[key] = next;
      i++;
    } else {
      args[key] = true;
    }
  }
  return args;
}

function readEnvFile(file) {
  const out = {};
  if (!existsSync(file)) return out;
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const m = line.match(/^([A-Z_]+)=(.*)$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

function writeEnvFile(file, values) {
  const lines = [
    "# Generated by `npm run setup`. Do not commit this file.",
    `# Dendrite homeserver (client-facing port), no trailing slash.`,
    `DENDRITE_BASE_URL=${values.DENDRITE_BASE_URL}`,
    ``,
    `# Access token of a Dendrite server admin user.`,
    `DENDRITE_ADMIN_TOKEN=${values.DENDRITE_ADMIN_TOKEN}`,
    ``,
    `# Optional: registration_shared_secret from dendrite.yaml. Only needed for`,
    `# the register_user tool (shared-secret registration).`,
    `DENDRITE_REGISTRATION_SHARED_SECRET=${values.DENDRITE_REGISTRATION_SHARED_SECRET ?? ""}`,
    ``,
    `# --- MCP transport ---`,
    `# "stdio" (default): spawned directly by your agent. No network exposure.`,
    `# "http": Streamable HTTP server on MCP_HTTP_HOST:MCP_HTTP_PORT (requires MCP_AUTH_TOKEN).`,
    `MCP_TRANSPORT=${values.MCP_TRANSPORT}`,
    ``,
    `# Required when MCP_TRANSPORT=http. Bearer token gating /mcp.`,
    `MCP_AUTH_TOKEN=${values.MCP_AUTH_TOKEN ?? ""}`,
    ``,
    `# Only used when MCP_TRANSPORT=http.`,
    `MCP_HTTP_HOST=${values.MCP_HTTP_HOST ?? "0.0.0.0"}`,
    `MCP_HTTP_PORT=${values.MCP_HTTP_PORT ?? "3939"}`,
    ``,
  ];
  writeFileSync(file, lines.join("\n"), { mode: 0o600 });
}

function run(cmd, args, opts = {}) {
  const res = spawnSync(cmd, args, { stdio: "inherit", ...opts });
  if (res.error) {
    console.error(`\n[setup] failed to run '${cmd}': ${res.error.message}`);
    process.exit(1);
  }
  if (res.status !== 0) {
    console.error(
      `\n[setup] '${cmd} ${args.join(" ")}' failed (exit ${res.status ?? "signal " + res.signal}).`,
    );
    process.exit(1);
  }
}

