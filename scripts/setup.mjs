async function main() {
  const args = parseArgs(process.argv.slice(2));
  const interactive = Boolean(input.isTTY);
  const rl = interactive ? createInterface({ input, output }) : null;

  const ask = async (prompt, current) => {
    if (!rl) return current;
    const answer = await rl.question(`${prompt} [${current || "none"}]: `);
    return answer.trim() || current;
  };

  const existing = readEnvFile(ENV_FILE);

  const resolve = async (key, flag, prompt, example, { optional = false } = {}) => {
    if (args[flag] !== undefined) {
      if (args[flag] === true) {
        throw new Error(`[setup] --${flag} requires a value (got a bare flag).`);
      }
      return String(args[flag]);
    }
    if (process.env[key]) return process.env[key];
    if (existing[key]) return existing[key];
    if (interactive) {
      let answer = "";
      do {
        answer = (await ask(`${prompt} (e.g. ${example})`, "")).trim();
        if (!answer && !optional) {
          console.log(`[setup] ${key} is required — please enter a value.`);
        }
      } while (!answer && !optional);
      return answer;
    }
    if (optional) return undefined;
    throw new Error(
      `[setup] ${key} is required. Pass --${flag} <value>, export ${key}, or run interactively.`,
    );
  };

  console.log(`\n[dendrite-admin-mcp] setup in ${ROOT}\n`);
  if (interactive) {
    console.log(
      "[setup] Note: secret values are echoed as you type (they are also saved to .env).\n",
    );
  }

  // Node version check.
  const nodeMajor = Number(process.versions.node.split(".")[0]);
  if (nodeMajor < 18) {
    console.error(`[setup] Node >= 18 required (found ${process.versions.node}).`);
    process.exit(1);
  }

  // Resolve values.
  const values = {};
  for (const v of REQUIRED_VARS) {
    values[v.key] = await resolve(v.key, v.flag, v.prompt, v.example);
  }
  for (const v of OPTIONAL_VARS) {
    const val = await resolve(v.key, v.flag, v.prompt, v.example, { optional: true });
    if (val) values[v.key] = val;
  }

  values.MCP_TRANSPORT = (args.transport || process.env.MCP_TRANSPORT || existing.MCP_TRANSPORT || "stdio").toLowerCase();
  if (interactive) {
    const answer = await ask(
      "MCP transport (stdio = spawned by your agent, http = network server)",
      values.MCP_TRANSPORT,
    );
    if (answer) values.MCP_TRANSPORT = answer.toLowerCase();
  }
  if (!["stdio", "http"].includes(values.MCP_TRANSPORT)) {
    console.error(`[setup] MCP_TRANSPORT must be 'stdio' or 'http' (got '${values.MCP_TRANSPORT}').`);
    process.exit(1);
  }

  if (values.MCP_TRANSPORT === "http") {
    if (args["mcp-token"] === true) {
      console.error("[setup] --mcp-token requires a value (got a bare flag).");
      process.exit(1);
    }
    values.MCP_AUTH_TOKEN =
      args["mcp-token"] || process.env.MCP_AUTH_TOKEN || existing.MCP_AUTH_TOKEN || randomBytes(32).toString("hex");
    if (interactive) {
      const answer = await ask(
        `MCP_AUTH_TOKEN (bearer token gating /mcp; blank to generate one)`,
        values.MCP_AUTH_TOKEN,
      );
      values.MCP_AUTH_TOKEN = answer || values.MCP_AUTH_TOKEN;
    }
    if (interactive) {
      console.log(`[setup] MCP_AUTH_TOKEN: ${values.MCP_AUTH_TOKEN}`);
    } else {
      console.log("[setup] MCP_AUTH_TOKEN written to .env (read it from there).");
    }
  }

  // Write .env.
  if (existsSync(ENV_FILE)) {
    console.log(`[setup] ${ENV_FILE} already exists — it will be overwritten.`);
  }
  writeEnvFile(ENV_FILE, values);
  console.log(`[setup] wrote ${ENV_FILE}`);

  // Install / build / test.
  if (!args["skip-install"]) {
    const lockfile = existsSync(path.join(ROOT, "package-lock.json"));
    console.log(`[setup] installing dependencies (${lockfile ? "npm ci" : "npm install"})...`);
    run("npm", lockfile ? ["ci"] : ["install"], { cwd: ROOT });
  }
  if (!args["skip-build"]) {
    console.log("[setup] building...");
    run("npm", ["run", "build"], { cwd: ROOT });
  }
  if (!args["skip-test"]) {
    console.log("[setup] running tests...");
    run("npm", ["test"], { cwd: ROOT });
  }

  if (rl) rl.close();

  // Print registration snippets.
  console.log("\n[setup] done. Register the server with your agent:\n");
  console.log(
    "NOTE: the commands below contain live secrets and will be stored in your shell history and\n" +
      "agent config. Prefer the env-var-indirection JSON forms where your agent supports them.\n",
  );
  console.log("--- Claude Code ---\n" + snippetClaudeCode(values) + "\n");
  console.log("--- Codex ---\n" + snippetCodex(values) + "\n");
  console.log("--- opencode ---\n" + snippetOpenCode(values) + "\n");
  console.log("--- GitHub Copilot ---\n" + snippetCopilot(values) + "\n");
  console.log("--- Pi ---\n" + snippetPi(values) + "\n");

  if (values.MCP_TRANSPORT === "http") {
    console.log(
      `[setup] HTTP transport: start with 'npm start', then point clients at http://<host>:${values.MCP_HTTP_PORT ?? "3939"}/mcp with 'Authorization: Bearer <MCP_AUTH_TOKEN>'.`,
    );
  } else {
    console.log(
      `[setup] stdio transport: the registration commands above spawn 'node ${DIST_INDEX}' directly. No server process to keep running.`,
    );
  }
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});